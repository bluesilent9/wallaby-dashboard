"""Public policy relationships; a cosigner key account is not a missing wallet replica."""
from vendor.embit.descriptor import Descriptor

def keys(raw):
    result=set()
    for row in raw.get('descriptors',[]):
        try:d=Descriptor.from_string(row['desc'].split('#')[0])
        except Exception:continue
        for key in d.keys:
            # Origins are annotations. The actual extended public key and suffix identify control.
            k=key.to_string().split(']')[-1].replace("'",'h');result.add(k)
    return result

def shared(raw):
    for row in raw.get('descriptors',[]):
        try:
            d=Descriptor.from_string(row['desc'].split('#')[0])
            if len(d.keys)>1 or d.witness_script() and 'after(' in row['desc']:return True
        except Exception:continue
    return False

def signing_account(account,monitor):
    if not account.get('private_keys_enabled') or not shared(monitor['raw']):return False
    own=keys(account['raw']);wanted=keys(monitor['raw'])
    if not own or not own<=wanted:return False
    # Signing accounts generated by the Agent have only wpkh receive/change branches.
    return all(r['desc'].startswith('wpkh(') for r in account['raw'].get('descriptors',[]))

def cosigner_accounts(wallets):
    monitors=[w for w in wallets if shared(w['raw'])]
    return [w for w in wallets if any(signing_account(w,m) for m in monitors if w is not m)]


def multisig_summary(raw):
    """Read thresholds from descriptor structure, never wallet names or labels."""
    from vendor.embit.descriptor.miniscript import Multi
    found=set()
    def walk(node):
        if isinstance(node,Multi):found.add((node.args[0].num,len(node.args)-1))
        for child in getattr(node,'args',[]):walk(child)
    for row in raw.get('descriptors',[]):
        try:
            d=Descriptor.from_string(row['desc'].split('#')[0]);walk(d.miniscript)
        except (ValueError,AttributeError):continue
    return [{'required':m,'total':n} for m,n in sorted(found) if n>1]
